"""Build everything the FM27 Hebrew pack needs.

    python tools/build.py [--ltc] [--rtl rli|rli-whole|rle|rlm|none] [--genders 0]
                          [--no-fonts] [--no-langdb] [--game <install>]

Inputs (all only read): translation/he/units.json ({first ltf key of the unit: text or {m, f}}, Hebrew only),
work/en/units.json + key_unit.json (the English, regenerated by tools/extract.py from the user's template
Documents\\...\\languages\\example.ltf), the game's font bundles and lang_db.dat (the DB names' English),
translation/he/dbnames/*.json, fonts/src, the proxy built in work/proxy-target.

Outputs:
  work/pack/files/                launcher filesDir (our own files only)
    version.dll                   the proxy (work/proxy-target/release/tirgumim_proxy.dll)
    tirgumim/he/redirect.cfg      pack/redirect.cfg = option A (FM compiles our hebrew.ltf)
    tirgumim/he/current_language.xml, hebrew.ltf
    tirgumim/he/hebrew.ltc, redirect-b.cfg, redirect-b-ltc-only.cfg      (--ltc: option B)
  work/build/                     modified copies of game files; make-pack turns them into bsdiff patches
    ui-fonts_assets_production_he.bundle, ui-styles_assets_common_he.bundle, ui-styles_assets_default_he.bundle
    lang_db_he.dat                (tools/langdb_write.py on translation/he/dbnames)
  work/pack/game/                 the whole thing as it goes into the game folder (hard links), for a manual
                                  test: copy its contents next to fm.exe
  work/pack/report.json           the numbers printed at the end, plus the keys left in English

hebrew.ltf (option A), per family (a base key and its -M/-F/-MF/-A... variants; each suffix letter is the
gender of one [%person#N] / [%team#N] of the base, in order of appearance):
  - split unit {m, f}: base STR = m (with [%male#N]; a [%male#N-hidden] is added if it has none), every
    variant whose own English has [%male#N] for the split person N gets m, [%female#N] gets f (with a
    [%female#N-hidden] if needed). If the engine skips records whose gender tokens do not fit the people
    passed in, a woman then gets the f text (README, "Gendered records and DB names").
  - plain unit: base STR = the Hebrew; a variant gets its own unit's Hebrew if that is translated, else the
    base Hebrew if its English equals the base English up to gender tokens, else STR stays empty (= English,
    counted in the report).
  - FM's compile rules (tools/ltc_write.py): an STR is one line (newlines written as \\n), [...] that is not
    a [% token is removed, \\" \\' \\\\ \\n are escapes, the text is trimmed, a family whose English is empty
    after that is dropped (it is left out of the ltf).
  - RTL marks (--rtl, default rli): RLI U+2067 ... PDI U+2069 around every line that has Hebrew letters
    (rli-whole: around the whole string, as in the 2026-11-25 test; rle: RLE...PDF; rlm: RLM prefix).
  - Header: LANGNAME Hebrew, GENDERS 0 (the research found GENDERS does not change FM's compile at all),
    BASESTRINGS 0.
hebrew.ltc (option B, --ltc): one record per family, split units [m, f] (French form, no base), all others
[text]; header source size = size of the hebrew.ltf next to it, and its mtime is set after the ltf's so FM
does not see it as stale.
"""
