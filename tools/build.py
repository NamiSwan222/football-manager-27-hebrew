FILES = os.path.join(WORK, 'pack', 'files')
HE = os.path.join(FILES, 'tirgumim', 'he')
BUILD = os.path.join(WORK, 'build')
GAME_COPY = os.path.join(WORK, 'pack', 'game')
PROXY = os.path.join(WORK, 'proxy-target', 'release', 'tirgumim_proxy.dll')
GAME = r'D:\SteamLibrary\steamapps\common\Football Manager 27'
AA = r'fm_Data\StreamingAssets\aa\StandaloneWindows64'
TEMPLATE = ltc_write.TEMPLATE

RLI, PDI, RLE, PDF, RLM = '⁧', '⁩', '‫', '‬', '‏'
HEBREW = re.compile('[֐-׿]')
PRON = r'(?:he|she|his|her|hers|him|himself|herself|He|She|His|Her|Hers|Him|Himself|Herself)'
PRONOUN = re.compile(r'\[%person#(\w+)-' + PRON + r'\]')

# font slots (Font objects) whose embedded TTF becomes Noto Sans + Noto Sans Hebrew (README, Rendering)
FONT_BUNDLES = {
    'ui-fonts_assets_production.bundle': ('LanguageFallback', 'ABCSocial-Regular', 'ABCSocialCondensed-Regular',
                                          'GT-America-Standard-Black', 'NotoSans-Regular', 'ExtraGlyphs-Regular'),
    'ui-styles_assets_common.bundle': ('NotInter-Regular',),
    'ui-styles_assets_default.bundle': ('NotInter-Regular',),
}


# ---- texts ------------------------------------------------------------------------------------------

def norm(s):
    """English with gender made neutral: [%male#1-he] / [%female#1-she] -> [%person#1-PRON], [%male_team#1 -> [%team#1."""
    s = re.sub(r'\[%(?:male|female|person)#(\w+)-' + PRON + r'\]', r'[%person#\1-PRON]', s)
    s = re.sub(r'\[%(?:male|female)#', '[%person#', s)
    return re.sub(r'\[%(?:male|female)_(\w+)#', r'[%\1#', s)  # -A/-B: [%male_team#1, [%female_club#1


def rtl_wrap(s, mode):
    if mode == 'none' or not HEBREW.search(s):
        return s
    if mode == 'rli-whole':
        return RLI + s + PDI
    pre, post = {'rli': (RLI, PDI), 'rle': (RLE, PDF), 'rlm': (RLM, '')}[mode]
    return '\n'.join(pre + ln + post if HEBREW.search(ln) else ln for ln in s.split('\n'))


def final(src, mode):
    """The string FM ends up with for an STR written from `src` (ltf form: \\n escapes, maybe [notes])."""
    return rtl_wrap(ltc_write.fm_text(src.replace('\n', '\\n')), mode)


def escape(s):
    """FM-side string -> one-line STR that FM's compile turns back into exactly `s`."""
    return s.replace('\\', '\\\\').replace('\n', '\\n')


def split_person(en, m):
    t = re.search(r'\[%male#(\w+)', m) or PRONOUN.search(en) or re.search(r'\[%person#(\w+)', en)
    return t.group(1) if t else '1'


def with_gender(m, f, p):
    if not re.search(r'\[%male#', m):
        m += f'[%male#{p}-hidden]'
    if not re.search(r'\[%female#', f):
        f += f'[%female#{p}-hidden]'
    return m, f


def var_gender(ven, p):
    if re.search(r'\[%female#' + re.escape(p) + r'(?=[\]\-])', ven):
        return 'f'
    if re.search(r'\[%male#' + re.escape(p) + r'(?=[\]\-])', ven):
        return 'm'
    return None


def load_units():
    """({English text: unit number}, {unit number: Hebrew | {m, f}}): English from work/en, Hebrew from
    translation/he/units.json (keyed by ltf key, see tools/extract.py)."""
    units = extract.load_units()
    tr, problems = extract.load_he()
    for p in problems[:10]:
        print('! translation/he/units.json', p)
    uid = {u['en']: u['u'] for u in units}
    return uid, tr


def plan(entries, uid, tr, rtl='rli'):
    """Per-key result for both options.
    Returns (strs {key: FM-side text or None = English}, records_b {ltc id: [texts]}, dropped keys, stats,
    english [(key, reason)])."""
    fam = collections.OrderedDict()
    for k, en in entries:
        fam.setdefault(k.split('-')[0], []).append((k, en))
    strs, recs, dropped, english = {}, {}, [], []
    st = collections.Counter()
    for b, es in fam.items():
        es.sort(key=lambda e: '-' in e[0])
        braw = es[0][1]
        if not ltc_write.fm_text(braw):
            dropped += [k for k, _ in es]
            st['families dropped (empty English)'] += 1
            continue
        st['families'] += 1
        ben = ltf.plain(braw)
        he = tr.get(uid.get(ben))
        rid = ltc_write.ID_BASE + int(b)
        if not he:
            st['base keys left English (unit not translated)'] += 1
            english.append((b, 'base unit not translated'))
            for k, _ in es:
                strs[k] = None
            recs[rid] = [ltc_write.fm_text(braw)]
            continue
        if isinstance(he, dict):
            p = split_person(ben, he['m'])
            if len(set(re.findall(r'\[%male#(\w+)', he['m']))) > 1:
                st['split units naming several people (first one decides)'] += 1
            m, f = with_gender(he['m'], he['f'], p)
            m, f = final(m, rtl), final(f, rtl)
            strs[b] = m
            recs[rid] = [m, f]
            st['base keys Hebrew (split m/f)'] += 1
            for k, ven in es[1:]:
                g = var_gender(ltf.plain(ven), p)
                if g is None:
                    st['variants of split units: person not gendered in variant, got m'] += 1
                strs[k] = f if g == 'f' else m
                st[f'variant keys Hebrew ({"f" if g == "f" else "m"} text of a split unit)'] += 1
                if norm(ltf.plain(ven)) != norm(ben):
                    st['  of those: variant English differs from the base beyond gender'] += 1
            continue
        h = final(he, rtl)
        strs[b] = h
        recs[rid] = [h]
        st['base keys Hebrew (one text)'] += 1
        for k, ven in es[1:]:
            ven = ltf.plain(ven)
            own = tr.get(uid.get(ven))
            if own:
                if isinstance(own, dict):
                    p = split_person(ven, own['m'])
                    om, of = with_gender(own['m'], own['f'], p)
                    own = of if var_gender(ven, p) == 'f' else om
                strs[k] = final(own, rtl)
                st['variant keys Hebrew (own unit)'] += 1
            elif norm(ven) == norm(ben):
                strs[k] = h
                st['variant keys Hebrew (base text, same English up to gender)'] += 1
            else:
                strs[k] = None
                loose = lambda s: re.sub(r'(?:\\n|\s)+$', '', norm(s))
                why = 'variant English differs from base only in trailing line breaks' if loose(ven) == loose(ben) \
                    else 'variant English differs from base'
                st[f'variant keys left English ({why})'] += 1
                english.append((k, why))
    return strs, recs, dropped, st, english


# ---- outputs ----------------------------------------------------------------------------------------

def write_ltf(path, entries, strs, genders):
    kept = [(k, en) for k, en in entries if k in strs]
    ltf.write(path, 'Hebrew', kept, {k: escape(s) for k, s in strs.items() if s}, genders=genders)
    return len(kept)


def write_cfgs(ltc):
    base = open(os.path.join(ROOT, 'pack', 'redirect.cfg'), encoding='utf-8').read()
    open(os.path.join(HE, 'redirect.cfg'), 'w', encoding='utf-8', newline='\n').write(base)
    if not ltc:
        return
    ltf_line = next(ln for ln in base.splitlines() if ln.startswith('place=') and ln.endswith('=hebrew.ltf'))
    ltc_line = ltf_line.replace('hebrew.ltf', 'hebrew.ltc')
    # the ltc is placed after the ltf (cfg order), so it stays the newer file
    b = base.replace(ltf_line, ltf_line + '\n' + ltc_line)
    open(os.path.join(HE, 'redirect-b.cfg'), 'w', encoding='utf-8', newline='\n').write(b)
    open(os.path.join(HE, 'redirect-b-ltc-only.cfg'), 'w', encoding='utf-8', newline='\n').write(
        base.replace(ltf_line, ltc_line))


def font_ttf(wght, wdth):
    """Noto Sans + Noto Sans Hebrew (OFL) as one static TTF (cached in work/build/fonts)."""
    from fontTools.merge import Merger
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer
    d = os.path.join(BUILD, 'fonts')
    out = os.path.join(d, f'tirgumim-noto-{wght}-{wdth:g}.ttf')
    if os.path.exists(out):
        return out
    os.makedirs(d, exist_ok=True)
    parts = []
    for i, src in enumerate(['notosans__NotoSans.ttf', 'notosanshebrew__NotoSansHebrew.ttf']):
        f = TTFont(os.path.join(ROOT, 'fonts', 'src', src))
        inst = instancer.instantiateVariableFont(f, {'wght': wght, 'wdth': wdth})
        for tag in ('STAT', 'MVAR', 'HVAR', 'meta', 'DSIG'):
            if tag in inst:
                del inst[tag]
        p = os.path.join(d, f'_part{i}.ttf')
        inst.save(p)
        parts.append(p)
    m = Merger().merge(parts)
    for rec in m['name'].names:
        if rec.nameID in (1, 3, 4, 16):
            rec.string = f'Tirgumim Noto {wght} {wdth:g}'
        elif rec.nameID == 6:
            rec.string = f'TirgumimNoto-{wght}-{int(wdth)}'
    m.save(out)
    for p in parts:
        os.remove(p)
    return out


def build_fonts(game):
    import UnityPy
    out = {}
    for name, slots in FONT_BUNDLES.items():
        env = UnityPy.load(os.path.join(game, AA, name))
        done = []
        for o in env.objects:
            if o.type.name != 'Font':
                continue
            t = o.read_typetree()
            if t['m_Name'] not in slots:
                continue
            n = t['m_Name'].lower()
            ttf = font_ttf(900 if 'black' in n else 400, 75.0 if 'condensed' in n else 100.0)
            t['m_FontData'] = list(open(ttf, 'rb').read())
            o.save_typetree(t)
            done.append(t['m_Name'])
        missing = set(slots) - set(done)
        if missing:
            sys.exit(f'{name}: font slots not found: {sorted(missing)} (game update?)')
        dst = os.path.join(BUILD, name.replace('.bundle', '_he.bundle'))
        open(dst, 'wb').write(env.file.save(packer='lz4'))
        out[os.path.basename(dst)] = done
    return out


def link_or_copy(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.exists(dst):
        os.remove(dst)
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ltc', action='store_true', help='also write option B: hebrew.ltc + redirect-b*.cfg')
    ap.add_argument('--rtl', default='rli', choices=['rli', 'rli-whole', 'rle', 'rlm', 'none'])
    ap.add_argument('--genders', type=int, default=0)
    ap.add_argument('--no-fonts', action='store_true', help='keep the font bundles already in work/build')
    ap.add_argument('--no-langdb', action='store_true', help='keep the lang_db_he.dat already in work/build')
    ap.add_argument('--game', default=GAME)
    a = ap.parse_args()
    t0 = time.time()
    if os.path.isdir(HE):
        for f in os.listdir(HE):
            os.remove(os.path.join(HE, f))
    os.makedirs(HE, exist_ok=True)
    os.makedirs(BUILD, exist_ok=True)
    report = {'rtl': a.rtl, 'genders': a.genders}

    # 1. hebrew.ltf
    entries = ltf.read(TEMPLATE)[1]
    uid, tr = load_units()
    strs, recs, dropped, st, english = plan(entries, uid, tr, a.rtl)
    ltf_path = os.path.join(HE, 'hebrew.ltf')
    n = write_ltf(ltf_path, entries, strs, a.genders)
    keys = {'template keys': len(entries), 'keys written': n, 'keys dropped (empty English, FM drops them too)':
            len(dropped), 'keys with Hebrew': sum(1 for s in strs.values() if s),
            'keys left English': sum(1 for s in strs.values() if not s)}
    report['keys'] = keys
    report['families'] = dict(st)
    report['english'] = english
    print('hebrew.ltf:', n, 'keys')

    # 2. option B
    if a.ltc:
        ltc = ltc_write.assemble('Hebrew', os.path.getsize(ltf_path), recs)
        ltc_path = os.path.join(HE, 'hebrew.ltc')
        ltc_write.write(ltc_path, ltc)
        mt = os.path.getmtime(ltf_path) + 60
        os.utime(ltc_path, (mt, mt))
        report['ltc'] = {'records': len(ltc['records']), 'split [m, f]': sum(1 for r in recs.values() if len(r) == 2),
                         'source size': ltc['source_size']}
        print('hebrew.ltc:', len(ltc['records']), 'records')
    write_cfgs(a.ltc)
    shutil.copy(os.path.join(ROOT, 'pack', 'current_language.xml'), HE)

    # 3. lang_db_he.dat
    langdb_out = os.path.join(BUILD, 'lang_db_he.dat')
    if not a.no_langdb:
        r = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'langdb_write.py'), '--out', langdb_out],
                           capture_output=True, text=True, encoding='utf-8')
        print(r.stdout.strip())
        if r.returncode:
            sys.exit('langdb_write.py failed:\n' + r.stderr)
        report['langdb_write'] = r.stdout.strip().splitlines()

    # 4. fonts, proxy, game-folder copy
    if not a.no_fonts:
        report['fonts'] = build_fonts(a.game)
        print('font bundles:', report['fonts'])
    if not os.path.exists(PROXY):
        sys.exit('proxy not built: ' + PROXY)
    if os.path.getmtime(PROXY) < os.path.getmtime(os.path.join(ROOT, 'tools', 'proxy', 'src', 'lib.rs')):
        print('! proxy DLL is older than tools/proxy/src/lib.rs: rebuild it (tools/proxy/build.cmd version ...)')
    shutil.copy2(PROXY, os.path.join(FILES, 'version.dll'))
    missing = []
    if os.path.isdir(GAME_COPY):
        shutil.rmtree(GAME_COPY)
    for dp, _, fs in os.walk(FILES):
        for f in fs:
            p = os.path.join(dp, f)
            link_or_copy(p, os.path.join(GAME_COPY, os.path.relpath(p, FILES)))
    for line in open(os.path.join(HE, 'redirect.cfg'), encoding='utf-8'):
        if line.startswith('map='):
            f = line.strip().rsplit('=', 1)[1]
            if os.path.exists(os.path.join(BUILD, f)):
                link_or_copy(os.path.join(BUILD, f), os.path.join(GAME_COPY, 'tirgumim', 'he', f))
            else:
                missing.append(f)

    # 5. report
    sizes = {}
    for dp, _, fs in os.walk(GAME_COPY):
        for f in fs:
            sizes[os.path.relpath(os.path.join(dp, f), GAME_COPY).replace('\\', '/')] = os.path.getsize(os.path.join(dp, f))
    report['sizes'] = sizes
    report['missing'] = missing
    import coverage
    report['dbnames'] = coverage.dbnames()
    json.dump(report, open(os.path.join(WORK, 'pack', 'report.json'), 'w', encoding='utf-8'), ensure_ascii=False,
              indent=1)
    print('\nkeys:')
    for k, v in keys.items():
        print(f'  {k:50} {v:8,}')
    print('families:')
    for k, v in sorted(st.items()):
        print(f'  {k:78} {v:8,}')
    print('DB names (translation/he/dbnames):')
    coverage.print_dbnames(report['dbnames'])
    print('sizes (work/pack/game):')
    for k, v in sorted(sizes.items()):
        print(f'  {k:55} {v / 1e6:9.1f} MB')
    for f in missing:
        print('! missing (cfg maps it, not built):', f)
    print(f'done in {time.time() - t0:.0f} s; keys left in English listed in work/pack/report.json')


if __name__ == '__main__':
    main()
